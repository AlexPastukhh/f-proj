import fs = require('node:fs');
import path = require('node:path');
import crypto = require('node:crypto');

export const PORTABLE_HTML_MARKER='<!-- Generated by Feature Projection; local-only snapshot. -->';
export const PORTABLE_HTML_FILENAME='projection.html';

// Do not create or overwrite anything inside the workspace by default.
export function resolvePortableHtmlDirectory(
  globalStorageRoot:string, workspaceRoot:string, configuredDirectory?:string,
):string {
  if (!path.isAbsolute(globalStorageRoot) || !path.isAbsolute(workspaceRoot))
    throw new Error('Portable HTML requires absolute storage/workspace paths');
  if (configuredDirectory?.trim()) {
    const dir=configuredDirectory.trim();
    if (!path.isAbsolute(dir)) throw new Error(
      'Portable HTML directory must be an absolute path for your localhost server');
    return path.resolve(dir);
  }
  const identity=fs.realpathSync(workspaceRoot);
  const digest=crypto.createHash('sha256').update(identity).digest('hex').slice(0,20);
  return path.join(globalStorageRoot,'portable-projections',digest);
}
function inspectDestination(file:string):void {
  if (!fs.existsSync(file)) return;
  const info=fs.lstatSync(file);
  if (!info.isFile() || info.isSymbolicLink())
    throw new Error('Portable HTML destination must be a regular generated file');
  const handle=fs.openSync(file,'r');
  try {
    const header=Buffer.alloc(Buffer.byteLength(PORTABLE_HTML_MARKER)+64);
    const n=fs.readSync(handle,header,0,header.length,0);
    if (!header.subarray(0,n).toString('utf8').includes(PORTABLE_HTML_MARKER))
      throw new Error('Refusing to overwrite a non-Feature-Projection HTML file');
  } finally {fs.closeSync(handle);}
}
export function writePortableHtmlAtomic(
  directory:string, htmlDocument:string,
):{file:string;changed:boolean} {
  if (!path.isAbsolute(directory)) throw new Error('Portable HTML directory must be absolute');
  if (!htmlDocument.startsWith('<!doctype html>\n'+PORTABLE_HTML_MARKER+'\n'))
    throw new Error('Not a generated Feature Projection HTML document');
  if (!fs.existsSync(directory)) fs.mkdirSync(directory,{recursive:true});
  const folder=fs.realpathSync(directory);
  const file=path.join(folder,PORTABLE_HTML_FILENAME);
  inspectDestination(file);
  if (fs.existsSync(file) && fs.readFileSync(file,'utf8')===htmlDocument)
    return {file,changed:false};
  const temp=path.join(folder,'.projection-'+crypto.randomBytes(12).toString('hex')+'.tmp');
  try {
    fs.writeFileSync(temp,htmlDocument,{flag:'wx',encoding:'utf8',mode:0o600});
    inspectDestination(file);
    fs.renameSync(temp,file);
  } finally {
    try{fs.unlinkSync(temp);}catch(err:any){if(err?.code!=='ENOENT')throw err;}
  }
  return {file,changed:true};
}

// The localhost app's generated HTML can live beneath a watched framework
// root. Ignore ONLY our exact output and atomic temp files, so Refresh
// does not trigger its own Stale notification. Never ignore sibling files.
export function isPortableHtmlOutputPath(
  candidate:string, configuredDirectory?:string,
):boolean {
  if (!configuredDirectory?.trim() || !path.isAbsolute(configuredDirectory.trim()))
    return false;
  const full=path.resolve(candidate);
  const folder=path.resolve(configuredDirectory.trim());
  const eq=(a:string,b:string)=>process.platform==='win32'?
    a.toLowerCase()===b.toLowerCase():a===b;
  if (!eq(path.dirname(full),folder)) return false;
  const name=path.basename(full);
  return eq(name,PORTABLE_HTML_FILENAME) || /^\.projection-[0-9a-f]{24}\.tmp$/i.test(name);
}
